from playwright.sync_api import sync_playwright
import json
with sync_playwright() as pw:
 browser=pw.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 page=browser.new_page(viewport={'width':1600,'height':900},device_scale_factor=1)
 errors=[]
 page.on('pageerror', lambda e:errors.append(str(e)))
 page.on('console', lambda m:errors.append('CONSOLE '+m.text) if m.type=='error' else None)
 from pathlib import Path
 src=Path('/mnt/data/second-key-game')
 html=(src/'index.html').read_text()
 html=html.replace('<script src="game.js" defer></script>','')
 html=html.replace('<link rel="stylesheet" href="styles.css" />','')
 # Resolve all art locally through an intercepted fake origin. No real requests leave the browser.
 page.route('**/assets/**',lambda route:route.fulfill(body=(src/'assets'/route.request.url.split('/assets/')[-1]).read_bytes(),content_type=('audio/ogg' if route.request.url.endswith('.ogg') else 'image/svg+xml')))
 html=html.replace('<head>','<head><base href="https://offline-asset.test/">')
 page.set_content(html,wait_until='domcontentloaded')
 page.add_style_tag(content='\n'.join((src/'styles.css').read_text().splitlines()[1:]))
 page.add_script_tag(content=(src/'game.js').read_text())
 page.screenshot(path='/mnt/data/second-key-game/tests/menu.png')
 print('menu',page.locator('[data-menu=new]').is_visible())
 page.locator('[data-menu=new]').click()
 page.wait_for_timeout(1000)
 print('game',page.locator('#game-screen').is_visible(),'choices',page.locator('.choice').count())
 print('state',page.evaluate('''() => {let s=__SECOND_KEY_TEST__.getState(); return [s.room,s.chapter,s.items]}'''))
 page.screenshot(path='/mnt/data/second-key-game/tests/game.png')
 page.locator('#journal-button').click();print('journal',page.locator('#modal-title').inner_text());page.locator('#modal-close').click()
 page.locator('#map-button').click();print('map',page.locator('#modal-title').inner_text());page.locator('#modal-close').click()
 page.locator('#pause-button').click();print('pause',page.locator('#modal-title').inner_text());page.locator('#pause-settings').click();print('settings',page.locator('#difficulty').count());page.locator('#save-settings').click()
 page.evaluate("__SECOND_KEY_TEST__.goRoom('evelyn')")
 page.evaluate("__SECOND_KEY_TEST__.act('camera')");print('items',page.evaluate('__SECOND_KEY_TEST__.getState().items'))
 page.locator('#camera-button').click();print('photos',page.evaluate('__SECOND_KEY_TEST__.getState().photos.length'))
 page.evaluate("__SECOND_KEY_TEST__.goRoom('kitchen')");page.evaluate("__SECOND_KEY_TEST__.act('mud')");print('chapter after mud',page.evaluate('__SECOND_KEY_TEST__.getState().chapter'))
 page.evaluate("__SECOND_KEY_TEST__.act('drawer')");print('chapter after drawer',page.evaluate('__SECOND_KEY_TEST__.getState().chapter'))
 page.evaluate('__SECOND_KEY_TEST__.chapter(4)');print('chapter 4',page.evaluate('__SECOND_KEY_TEST__.getState().chapter'))
 page.screenshot(path='/mnt/data/second-key-game/tests/kitchen.png')
 page.evaluate('__SECOND_KEY_TEST__.ending(3)');print('ending',page.locator('#ending-heading').inner_text())
 print('errors',json.dumps(errors,indent=2))
 browser.close()
 if errors:raise SystemExit(1)
